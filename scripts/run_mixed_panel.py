"""Human raters, local LLM raters, or both: which aggregator works best on each panel?

    python scripts/run_mixed_panel.py        # writes results/MIXED_PANEL.md

DICES-350, expert label as gold. Verifiers:
* humans: the 123 raters, Q_overall (Yes = 1, Unsure = 0, No = -1);
* LLMs: every results/llm_scores/350_<model>_<prompt>.csv (scripts/label_dices_local.py),
  score = log P(Yes) - log P(No) for "is the final response unsafe?".

The v4 prompt was tuned (for the GPT label) on the DEV half of DICES-350, so LLM verifiers that
use it have seen those conversations' expert labels indirectly. Every table is therefore also
reported on the TEST half alone, which is the clean number.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

from fuse import dices  # noqa: E402
from run_continuous import boot, methods  # noqa: E402

import label_dices_llm as L  # noqa: E402

SEEDS = 20


def load_llms(items):
    cols, names = [], []
    for f in sorted((ROOT / "results" / "llm_scores").glob("350_*.csv")):
        if "limit" in f.stem:
            continue
        s = pd.read_csv(f).set_index("item_id").logit_unsafe.reindex(items)
        if s.isna().any():
            continue
        cols.append(s.to_numpy())
        names.append(f.stem.replace("350_", "").replace("-it-qat-4bit", "").replace("-Instruct-4bit", "").replace("-4bit", ""))
    return np.column_stack(cols), names


def mean_offdiag_corr(V):
    V = V[:, V.std(0) > 0]  # a rater who gave one answer to everything has no correlation
    C = np.corrcoef(V.T)
    return float(C[~np.eye(len(C), dtype=bool)].mean())


def table(md, title, V, y, rows_idx=None):
    if rows_idx is not None:
        V, y = V[rows_idx], y[rows_idx]
    ms = methods(V)
    ref = ms["Dawid-Skene (5 bins)"][0]
    md += [f"#### {title}", "", "| Method | AUC | Accuracy | AUC vs D&S 5 bins (95% CI) |", "|---|---:|---:|---|"]
    out = {}
    for k, (s, prob) in ms.items():
        auc = 100 * roc_auc_score(y, s)
        acc = f"{100 * np.mean((s > 0.5) == y):.1f}" if prob else ""
        diff = "" if k == "Dawid-Skene (5 bins)" else boot(s, ref, y)
        md.append(f"| {k} | {auc:.1f} | {acc} | {diff} |")
        out[k] = auc
    md.append("")
    return out


def main():
    m = dices.build(dices.load("350"), "overall")
    y = m.gold.astype(int)
    items = L.conversations("350")
    test = np.isin(m.items, L.split_350(items)["test"])
    H = m.V
    X, names = load_llms(m.items)
    print(f"{len(names)} LLM verifiers: {names}")

    md = ["# Humans, local LLMs, or both (generated by scripts/run_mixed_panel.py)", "",
          "DICES-350, expert label as gold. LLM verifiers are local open-weight models scored by "
          "log P(Yes) - log P(No) (scripts/label_dices_local.py). AUC against the expert label.", ""]

    md += ["## Single LLM verifiers", "", "| Verifier | AUC all 350 | AUC test half | Accuracy at P = 0.5 (test) |", "|---|---:|---:|---:|"]
    for j, n in enumerate(names):
        md.append(f"| {n} | {100 * roc_auc_score(y, X[:, j]):.1f} | {100 * roc_auc_score(y[test], X[test, j]):.1f} | "
                  f"{100 * np.mean((X[test, j] > 0) == y[test]):.1f} |")
    md += ["", f"Mean pairwise correlation of scores: LLM verifiers {mean_offdiag_corr(X):.2f}, "
           f"human raters {mean_offdiag_corr(H):.2f}.", ""]

    for label, idx in [("test half (clean)", test), ("all 350", None)]:
        md += [f"## Panels, {label}", ""]
        table(md, "Humans only (123 raters)", H, y, idx)
        table(md, f"LLMs only ({len(names)} verifiers)", X, y, idx)
        table(md, f"Humans + LLMs ({123 + len(names)} verifiers)", np.c_[H, X], y, idx)

    # A realistic budget: a few humans per item, with or without the LLM verifiers.
    md += ["## Few humans, with and without LLMs (test half)", "",
           f"k random human raters (the same k for every item), mean AUC over {SEEDS} draws.", "",
           "| k humans | Panel | " + " | ".join(["MV (median split)", "D&S (5 bins)", "Mean z", "FUSE logistic", "FUSE product"]) + " |",
           "|---:|---|" + "---:|" * 5]
    keys = ["Majority vote (median split)", "Dawid-Skene (5 bins)", "Mean z-score", "FUSE logistic (paper)", "FUSE product posterior"]
    for k in [3, 5, 10]:
        for panel in ["humans", "humans + LLMs"]:
            res = []
            for seed in range(SEEDS):
                cols = np.random.default_rng(seed).choice(H.shape[1], k, replace=False)
                V = H[:, cols] if panel == "humans" else np.c_[H[:, cols], X]
                V, yy = V[test], y[test]
                if panel == "humans" and k < 3:
                    continue
                ms = methods(V)
                res.append({kk: 100 * roc_auc_score(yy, ms[kk][0]) for kk in keys})
            md.append(f"| {k} | {panel} | " + " | ".join(f"{np.mean([r[kk] for r in res]):.1f}" for kk in keys) + " |")
            print(k, panel, {kk: round(np.mean([r[kk] for r in res]), 1) for kk in keys}, flush=True)
    md.append("")
    (ROOT / "results" / "MIXED_PANEL.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
