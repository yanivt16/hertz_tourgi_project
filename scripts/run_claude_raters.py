"""DICES-350 with Claude raters (Sonnet, Haiku) next to humans and local LLMs, and "filling holes":
few humans per item, LLMs rate every item.

    python scripts/run_claude_raters.py      # writes results/CLAUDE_RATERS.md

Verifiers: the 123 human raters (Q_overall: Yes = 1, Unsure = 0, No = -1); the 6 local LLM
verifiers of scripts/run_mixed_panel.py; and two Claude raters (results/claude_scores/, made as
described in scripts/make_claude_rater_batches.py), each a 0-100 probability of "unsafe".
Gold = expert label. AUC is always on the TEST half (the v4 policy was tuned on the DEV half).

1. Single raters, correlations, and the residual detector on the 8 LLM verifiers.
2. Dense panels: all 123 humans, or the same k humans on every item, with or without LLMs
   (aggregators fitted on the test half, as in run_mixed_panel.py). Also the k-humans + 8 LLMs
   panel after merging each detected block into one verifier.
3. Filling holes, large pool: each item gets k humans drawn from all 123 (different humans per
   item). Aggregators are fitted on all 350 items (they see no labels).
4. Filling holes, small fixed team: P humans drawn once, each item gets k of them.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

from fuse import dices  # noqa: E402
from fuse.clustering import residual_groups  # noqa: E402
from fuse.ensemble import FUSE  # noqa: E402
from fuse.ordinal import dawid_skene_ordinal  # noqa: E402
from run_continuous import boot, methods  # noqa: E402
from run_mixed_panel import load_llms  # noqa: E402

import label_dices_llm as L  # noqa: E402

np.seterr(all="ignore")
SEEDS = 20

m = dices.build(dices.load("350"), "overall")
y = m.gold.astype(int)
test = np.isin(m.items, L.split_350(L.conversations("350"))["test"])
H = m.V
X, lnames = load_llms(m.items)
C = np.column_stack([pd.read_csv(ROOT / "results" / "claude_scores" / f"350_{c}.csv").set_index("item_id")
                     .p_unsafe.reindex(m.items).to_numpy(float) for c in ("sonnet", "haiku")])
cnames = ["Claude Sonnet", "Claude Haiku"]
A, anames = np.c_[X, C], lnames + cnames


def auc(s):
    return 100 * roc_auc_score(y[test], s[test])


def zmean(V):
    sd = np.nanstd(V, 0)
    return np.nanmean((V - np.nanmean(V, 0)) / np.where(sd > 0, sd, 1), 1)


def collapse(V, t=0.4):
    groups, _, _ = residual_groups(V, threshold=t)
    sd = V.std(0)
    Z = (V - V.mean(0)) / np.where(sd > 0, sd, 1)
    return np.column_stack([Z[:, g].mean(1) for g in groups])


DENSE = ["Majority vote (median split)", "Dawid-Skene (5 bins)", "Mean z-score", "FUSE logistic (paper)",
         "FUSE triplet posterior (paper)", "FUSE product posterior"]


def dense_table(md, title, V):
    ms = methods(V[test])
    ref = ms["Dawid-Skene (5 bins)"][0]
    md += [f"#### {title} ({V.shape[1]} verifiers)", "", "| Method | AUC | vs D&S 5 bins (95% CI) |", "|---|---:|---|"]
    for k in DENSE:
        s = ms[k][0]
        md.append(f"| {k} | {100 * roc_auc_score(y[test], s):.1f} | {'' if k == DENSE[1] else boot(s, ref, y[test])} |")
    md.append("")


def corr_table(R: pd.DataFrame) -> list[str]:
    out = ["| | " + " | ".join(R.columns) + " |", "|---|" + "---:|" * len(R.columns)]
    return out + [f"| {i} | " + " | ".join(f"{v:.2f}" for v in R.loc[i]) + " |" for i in R.index]


def skip_fuse(V, min_overlap=20):
    return FUSE(predictor="posterior", missing="skip", posterior_mode="product", min_overlap=min_overlap).fit_scores(V).scores


def main():
    md = ["# Claude raters on DICES-350, and filling holes (generated by scripts/run_claude_raters.py)", "",
          "AUC against the expert label on the test half (175 conversations). Few-human rows are means over "
          f"{SEEDS} random draws of humans; the count of draws in which one method beats another is shown "
          "instead of a confidence interval (all draws share the same 175 items).", ""]

    # 1. single raters
    hum = [100 * roc_auc_score(y[test], H[test, j]) for j in range(H.shape[1])]
    md += ["## 1. Single raters", "", "| Verifier | AUC test half |", "|---|---:|"]
    md += [f"| {n} | {auc(A[:, j]):.1f} |" for j, n in enumerate(anames)]
    md += [f"| Human rater, median of 123 [range] | {np.median(hum):.1f} [{min(hum):.1f}-{max(hum):.1f}] |", "",
           "Spearman correlation between LLM verifiers (all 350 items):", "",
           *corr_table(pd.DataFrame(A, columns=anames).corr(method="spearman")), "",
           "Residual detector on the 8 LLM verifiers (all 350 items, no labels):", ""]
    for t in (0.4, 0.3):
        g, _, _ = residual_groups(A, threshold=t)
        md.append(f"- threshold {t}: " + "; ".join(" + ".join(anames[i] for i in grp) for grp in g if len(grp) > 1))
    md.append("")

    # 2. dense panels
    md += ["## 2. Dense panels (every human in the panel rates every item)", ""]
    dense_table(md, "Claude only", C)
    dense_table(md, "All 8 LLMs", A)
    dense_table(md, "123 humans + Claude", np.c_[H, C])
    dense_table(md, "123 humans + 8 LLMs", np.c_[H, A])
    keys = ["Dawid-Skene (5 bins)", "Mean z-score", "FUSE logistic (paper)"]
    md += ["#### The same k humans on every item", "",
           "| k | Panel | D&S 5 bins | Mean z | FUSE logistic | FUSE > D&S | FUSE > mean z |", "|---:|---|---:|---:|---:|---:|---:|"]
    for k in (3, 5, 10):
        for pname, f in [("humans", lambda Hk: Hk), ("humans + Claude", lambda Hk: np.c_[Hk, C]),
                         ("humans + 8 LLMs", lambda Hk: np.c_[Hk, A]),
                         ("humans + 8 LLMs, blocks merged by detector", lambda Hk: collapse(np.c_[Hk, A][test]))]:
            r = []
            for seed in range(SEEDS):
                cols = np.random.default_rng(seed).choice(H.shape[1], k, replace=False)
                V = f(H[:, cols])
                V = V if V.shape[0] == test.sum() else V[test]
                ms = methods(V)
                r.append([100 * roc_auc_score(y[test], ms[kk][0]) for kk in keys])
            r = np.array(r)
            md.append(f"| {k} | {pname} | " + " | ".join(f"{v:.1f}" for v in r.mean(0)) +
                      f" | {(r[:, 2] > r[:, 0]).sum()}/{SEEDS} | {(r[:, 2] > r[:, 1]).sum()}/{SEEDS} |")
            print(k, pname, r.mean(0).round(1), flush=True)
    md.append("")

    # 3 and 4. filling holes
    def holes_rows(title, draw, configs):
        out = [f"## {title}", "", "| Pool | k per item | Shared items per pair of humans | Panel | Mean of the k humans | D&S 5 bins | Mean z | FUSE (missing-aware) |",
               "|---|---:|---:|---|---:|---:|---:|---:|"]
        for P, k in configs:
            res = {}
            for seed in range(SEEDS):
                S = draw(np.random.default_rng(seed), P, k)
                crowd = np.nanmean(S, 1)
                for pname, V in [("humans only", S), ("humans + Claude", np.c_[S, C]), ("humans + 8 LLMs", np.c_[S, A])]:
                    res.setdefault(pname, []).append([auc(crowd), auc(dawid_skene_ordinal(V, 5)), auc(zmean(V)), auc(skip_fuse(V, 5))])
            ov = 350 * k * (k - 1) / (P * (P - 1))
            for pname, r in res.items():
                out.append(f"| {P} | {k} | {ov:.1f} | {pname} | " + " | ".join(f"{v:.1f}" for v in np.mean(r, 0)) + " |")
                print(P, k, pname, np.mean(r, 0).round(1), flush=True)
        return out + [""]

    def draw_pool(rng, P, k):  # P = 123: the whole pool, different humans per item
        team = rng.choice(H.shape[1], P, replace=False)
        S = np.full((H.shape[0], P), np.nan)
        for i in range(H.shape[0]):
            c = rng.choice(P, k, replace=False)
            S[i, c] = H[i, team[c]]
        return S[:, ~np.isnan(S).all(0)]  # in the large pool a human can be drawn for no item

    md += holes_rows("3. Filling holes, large pool (each item gets k of all 123 humans)", draw_pool, [(123, 3), (123, 5)])
    md += holes_rows("4. Filling holes, small fixed team (P humans, each item gets k of them)", draw_pool,
                     [(6, 3), (10, 3), (15, 3), (10, 5), (20, 5)])
    md += ["FUSE here is the missing-aware version (moments over co-rated items, product posterior, the "
           "logistic predictor is not available with missing ratings) with min_overlap = 5.", ""]
    (ROOT / "results" / "CLAUDE_RATERS.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
