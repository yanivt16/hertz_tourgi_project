"""FUSE on VIPER (radiologists reading mammograms, gold = cancer at 455 days).

    pip install rdata
    python scripts/run_viper.py        # writes results/VIPER.md

The two .rda files are downloaded from github.com/DIDSR/viperData into .cache/viper.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import numpy as np  # noqa: E402

from fuse import viper  # noqa: E402

COLS = ["Method", "AUC", "Sens.", "Spec.", "AUC vs MV (95% CI)"]


def table(rows):
    out = ["| " + " | ".join(COLS) + " |", "|---|" + "---:|" * 3 + "---|"]
    for r in rows:
        out.append("| " + " | ".join(f"{r[c]:.1f}" if isinstance(r.get(c), float) else str(r.get(c, "")) for c in COLS) + " |")
    return "\n".join(out)


def section(md, title, reads, gold):
    S, B, y = viper.build(reads, gold)
    head = f"{len(y)} cases ({int(y.sum())} cancers), {S.shape[1]} readers, {100 * np.isnan(S).mean():.0f}% missing"
    print(f"\n{title}: {head}", flush=True)
    t = table(viper.evaluate(S, B, y))
    print(t)
    md += [f"### {title}", "", head, "", t, ""]


def main():
    reads, gold = viper.load()
    md = ["# FUSE on VIPER (generated by scripts/run_viper.py)", "",
          "Items = mammography cases, verifiers = radiologists, gold = cancer status at 455-day follow-up.",
          "AUC against cancer status. FUSE gets missing reads as 0 (each reader's column mapped to [-1, 1]).", ""]
    for mod in ["FFDM", "SFM"]:
        r = reads[reads.modalityID == mod]
        leak = viper.assignment_leak(r, gold)
        md += [f"## {mod}", "",
               f"Which radiologists read a case predicts cancer with cross-validated AUC **{100 * leak:.1f}**, "
               "using no scores at all. The full-matrix numbers below are therefore contaminated for any "
               "method that sees missing reads as values (FUSE here). The dense blocks have no missing reads.", ""]
        print(f"{mod}: assignment leak AUC {100 * leak:.1f}")
        section(md, f"{mod}, full matrix (missingness leaks the label)", r, gold)
        blocks = viper.dense_blocks(r)
        for lo in (90, 200):
            n, (Rs, cs) = max(((n, b) for n, b in blocks.items() if n >= lo), key=lambda t: len(t[1][0]))
            section(md, f"{mod}, dense block: {len(Rs)} readers x {n} cases", r[r.readerID.isin(Rs) & r.caseID.isin(cs)], gold)
    (ROOT / "results" / "VIPER.md").write_text("\n".join(md))


if __name__ == "__main__":
    main()
