"""Order-free FUSE on the paper's own Best-of-N data: does the fix cost accuracy where FUSE was built?

    python scripts/run_order_free_bon.py      # writes results/ORDER_FREE_BON.md

Settings: the paper's Weaver settings (MATH500, MMLU, MMLU-Pro, GPQA, GPQA-Diamond; Llama 3.1 8B
and 70B generators), HLE and IMO. The GPQA 70B dataset (hazyresearch/GPQA_with_Llama_3.1_70B_
Instruct_v1) no longer has its data on Hugging Face (README only), so GPQA-70B and GPQA-Diamond-70B
are skipped. Each benchmark is cached in .cache/bon/ after the first download.

For two configurations (per-question FUSE with the logistic predictor, and batched FUSE with the
posterior), selection accuracy (%) of:
  * paper FUSE in the dataset's verifier order;
  * paper FUSE with the verifier columns in random orders (the same permutation for every query),
    mean and min-max over ORDERS orders;
  * order-free FUSE (tci_symmetric=True, tci_search="greedy").
The paper's own FUSE number is shown for reference (it does not say which configuration it used).
"""

from __future__ import annotations

import pickle
import sys
import time
from dataclasses import replace
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from fuse import FUSE  # noqa: E402
from fuse.data import Benchmark, Query, download_fuse, download_weaver  # noqa: E402
from fuse.experiment import PAPER_RESULTS, run_unsupervised  # noqa: E402

np.seterr(all="ignore")
CACHE = ROOT / ".cache" / "bon"
ORDERS = 3
SETTINGS = [("weaver", b, s) for s in ("70b", "8b") for b in ("math500", "mmlu", "mmlu-pro", "gpqa", "gpqa-diamond")
            if not (s == "70b" and b.startswith("gpqa"))] + [("fuse", "hle", None), ("fuse", "imo", None)]
CONFIGS = [("per question, logistic", "query", "logistic"), ("batched, posterior", "batch", "posterior")]


def load(kind, b, s) -> Benchmark:
    name = b if s is None else f"{b}-{s}"
    path = CACHE / f"{name}.pkl"
    if path.exists():
        return pickle.loads(path.read_bytes())
    bench = download_fuse(b) if kind == "fuse" else download_weaver(b, s)
    CACHE.mkdir(parents=True, exist_ok=True)
    path.write_bytes(pickle.dumps(bench))
    return bench


def permuted(bench: Benchmark, perm) -> Benchmark:
    return replace(bench, verifiers=[bench.verifiers[i] for i in perm],
                   queries=[Query(q.qid, q.scores[:, perm], q.correct, q.answers, q.weaver_scores) for q in bench.queries])


def fuse_acc(bench, mode, predictor, **kw):
    return run_unsupervised(bench, FUSE(predictor=predictor, **kw), mode=mode, workers=8)["FUSE"]


def main():
    md = ["# Order-free FUSE on the paper's Best-of-N data (generated by scripts/run_order_free_bon.py)", "",
          f"Selection accuracy (%). Random order = the verifier columns permuted (same permutation for every query), "
          f"mean [min-max] over {ORDERS} orders. GPQA-70B and GPQA-Diamond-70B are skipped: their dataset is no longer "
          "on Hugging Face.", ""]
    for label, mode, predictor in CONFIGS:
        md += [f"## {label}", "", "| Setting | Verifiers | Paper's reported FUSE | Paper FUSE, dataset order | "
               "Paper FUSE, random order | Order-free FUSE | Order-free minus dataset order |", "|---|---:|---:|---:|---|---:|---:|"]
        diffs = []
        for kind, b, s in SETTINGS:
            t = time.time()
            bench = load(kind, b, s)
            name = bench.name
            base = fuse_acc(bench, mode, predictor)
            rnd = [fuse_acc(permuted(bench, np.random.default_rng(p).permutation(len(bench.verifiers))), mode, predictor)
                   for p in range(ORDERS)]
            free = fuse_acc(bench, mode, predictor, tci_symmetric=True, tci_search="greedy")
            diffs.append(free - base)
            md.append(f"| {name} | {len(bench.verifiers)} | {PAPER_RESULTS.get(name, {}).get('FUSE', float('nan')):.1f} | "
                      f"{base:.1f} | {np.mean(rnd):.1f} [{min(rnd):.1f}-{max(rnd):.1f}] | **{free:.1f}** | {free - base:+.1f} |")
            print(md[-1], f"({time.time() - t:.0f}s)", flush=True)
        md += ["", f"Mean change from the dataset order: {np.mean(diffs):+.2f} points over {len(diffs)} settings.", ""]
    (ROOT / "results" / "ORDER_FREE_BON.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
