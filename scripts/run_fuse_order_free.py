"""Order-free FUSE: a symmetric TCI statistic and a greedy threshold search (not in the paper).

    python scripts/run_fuse_order_free.py      # writes results/FUSE_ORDER_FREE.md

The paper's TCI statistic (Eq. 4) sums, for each verifier j3, the variance over pairs j1 < j2 < j3,
so it changes with the column order, and its coordinate descent visits verifiers in column order.
FUSE(tci_symmetric=True) uses every pair of the other verifiers for each j3;
FUSE(tci_search="greedy") applies the single best threshold move per step. Both together give the
same result in any column order (tests/test_fuse.py).

Same panels as scripts/run_fuse_order.py. Columns:
  * paper FUSE, mean AUC over 4 random column orders (what a user gets);
  * symmetric statistic with the paper's sequential search, mean over the same 4 orders;
  * symmetric + greedy (order-free; one run);
  * the four baselines of run_fuse_order.py and the best of them;
  * order-free FUSE minus the best baseline, and minus plain Dawid-Skene, with 95% over draws.
"""

from __future__ import annotations

import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

import run_fuse_order as O  # noqa: E402
from fuse import FUSE, crowd, dices  # noqa: E402

ORDERS = 4
BASE = ["D&S 5 bins", "Mean z", "D&S -> logistic", "Detector + D&S"]
HEAD = ["| Panel | Paper FUSE, random order | Symmetric TCI, random order | Order-free FUSE | D&S 5 bins | Mean z | "
        "D&S -> logistic | Detector + D&S | Order-free minus best baseline | Order-free minus D&S |",
        "|---|" + "---:|" * 9]


def ci(d):
    return f"{d.mean():+.1f} ± {1.96 * d.std() / np.sqrt(len(d)):.1f}"


def evaluate(panels):
    rows = []
    for name, draws in panels.items():
        t = time.time()
        r = {k: [] for k in ["paper", "sym", "free"] + BASE}
        for i, (V, y) in enumerate(draws):
            auc = lambda s: 100 * roc_auc_score(y, s)  # noqa: E731
            perms = [np.random.default_rng(1000 * i + p).permutation(V.shape[1]) for p in range(ORDERS)]
            r["paper"].append(np.mean([auc(FUSE().fit_scores(V[:, p]).scores) for p in perms]))
            r["sym"].append(np.mean([auc(FUSE(tci_symmetric=True).fit_scores(V[:, p]).scores) for p in perms]))
            r["free"].append(auc(FUSE(tci_symmetric=True, tci_search="greedy").fit_scores(V).scores))
            for k, s in O.baselines(V).items():
                r[k].append(auc(s))
        r = {k: np.array(v) for k, v in r.items()}
        best = max(BASE, key=lambda k: r[k].mean())
        rows.append(f"| {name} | {r['paper'].mean():.1f} | {r['sym'].mean():.1f} | **{r['free'].mean():.1f}** | "
                    + " | ".join(f"{r[k].mean():.1f}" for k in BASE)
                    + f" | {ci(r['free'] - r[best])} ({best}) | {ci(r['free'] - r['D&S 5 bins'])} |")
        print(rows[-1], f"({time.time() - t:.0f}s)", flush=True)
    return rows


def main():
    md = ["# Order-free FUSE (generated by scripts/run_fuse_order_free.py)", "",
          f"AUC. 'Random order' = mean over {ORDERS} random column orders of the same panel. Order-free FUSE = "
          "FUSE(tci_symmetric=True, tci_search='greedy'), which gives the same result in any order. "
          "± = 95% over draws (the best baseline is chosen after the fact, which favours the baselines).", ""]
    md += ["## 1. Simulation (10 seeds, 1000 items, 30% positive)", ""] + HEAD
    sims = {}
    for h, d, rho in [(5, 0.3, 0.0), (5, 0.3, 0.15), (5, 0.5, 0.15), (5, 0.5, 0.2), (10, 0.3, 0.3), (10, 0.3, 0.6)]:
        sims[f"{h} humans + 6 LLMs (d={d}), shared noise {rho}"] = [
            O.simulate(np.random.default_rng(s), 1000, h, 6, d, rho) for s in range(10)]
    md += evaluate(sims) + [""]

    import label_dices_llm as L
    from run_mixed_panel import load_llms
    m = dices.build(dices.load("350"), "overall")
    y = m.gold.astype(int)
    test = np.isin(m.items, L.split_350(L.conversations("350"))["test"])
    H, X = m.V, load_llms(m.items)[0]
    C = np.column_stack([pd.read_csv(ROOT / "results" / "claude_scores" / f"350_{c}.csv").set_index("item_id")
                         .p_unsafe.reindex(m.items).to_numpy(float) for c in ("sonnet", "haiku")])
    A = np.c_[X, C]
    md += ["## 2. DICES-350, test half (20 draws of humans)", ""] + HEAD
    pan = {}
    for k, name, extra in [(10, "8 LLMs", A), (10, "6 local LLMs", X), (5, "8 LLMs", A), (10, "Claude only", C), (10, "no LLMs", None)]:
        def panel(s, k=k, extra=extra):
            Hk = H[:, np.random.default_rng(s).choice(H.shape[1], k, replace=False)]
            return (Hk if extra is None else np.c_[Hk, extra])[test], y[test]
        pan[f"{k} humans + {name}"] = [panel(s) for s in range(20)]
    md += evaluate(pan) + [""]

    import run_correlated_block_rte as R
    Hr, gold = crowd.load("RTE")
    yr = gold.astype(int)
    Xr = {mm: np.column_stack([R.llm(mm, p) for p in ("short", "guide")]) for mm in R.SMALL}
    md += ["## 3. RTE (20 shuffles of each pair's labels into human columns)", ""] + HEAD
    pan = {}
    for name, nh, models in [("10 humans + 4 tiny Qwen", 10, R.TINY), ("10 humans + 8 small Qwen", 10, R.SMALL),
                             ("5 humans + 4 tiny Qwen", 5, R.TINY), ("3 humans + 4 tiny Qwen", 3, R.TINY),
                             ("10 humans, no LLMs", 10, [])]:
        def panel(dd, nh=nh, models=models):
            S = R.slots(Hr, np.random.default_rng(dd))[:, :nh]
            return (np.c_[S, np.column_stack([Xr[mm] for mm in models])] if models else S), yr
        pan[name] = [panel(dd) for dd in range(20)]
    md += evaluate(pan) + [""]
    (ROOT / "results" / "FUSE_ORDER_FREE.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
