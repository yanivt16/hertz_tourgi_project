"""FUSE on DICES-990, scored against an LLM safety label (DICES-990 has no expert verdict).

    python scripts/run_dices990.py --labels dices990_v3 --labels350 dev_v3 test_v3

DICES-990 is sparse: each conversation has about 73 of 172 raters, so about 58% of the
rater x conversation matrix is empty. Two ways of living with that are compared:

* per-rater views: missing ratings are imputed as the neutral value 0 (what the FUSE paper
  does with missing scores), optionally after dropping raters who rated fewer than 50 items;
* demographic-group views: each verifier is a group's share of Yes answers, which is defined
  for almost every conversation because each one is rated by ~73 raters across groups.

`--labels350` repeats the per-rater and group runs on DICES-350 twice, once scored against the
expert label and once against the LLM label from the same prompt, to show how far conclusions
drawn against the LLM label carry over to the expert one.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from fuse import FUSE, dices  # noqa: E402

RESULTS = ROOT / "results"
LABELS = RESULTS / "llm_labels"

SETTINGS_990 = [
    ("overall", None, None),
    ("overall-min50", None, 50),
    ("groups", ("rater_locale", "rater_gender"), None),
    ("groups", ("rater_locale", "rater_age"), None),
    ("groups", ("rater_locale", "rater_race"), None),
]
SETTINGS_350 = [("overall", None, None), ("groups", ("rater_race", "rater_gender"), None)]


def read_labels(names: list[str]) -> pd.DataFrame:
    lab = pd.concat([pd.read_csv(LABELS / f"{n}.csv") for n in names])
    return lab[lab.unsafe.notna()].drop_duplicates("item_id", keep="last")


def matrix(df, view, groups, min_items):
    base = "overall" if view.startswith("overall") else view
    m = dices.build(df, base, groups=groups or ("rater_race", "rater_gender"), min_group_raters=5 if groups else None)
    if groups:
        m.name += "-" + "x".join(g.replace("rater_", "") for g in groups)
    if min_items:
        m = dices.drop_sparse_raters(m, min_items)
    return m


def block(r: dict, extra: str = "") -> list[str]:
    info = r["fuse_info"]
    keep = {k: info[k] for k in ("n_verifiers", "n_kept", "estimated_prevalence", "fallback") if k in info}
    return [f"### {r['setting']}{extra}", "", r["summary"], "", dices.format_table(r), "", "```", json.dumps(keep), "```", ""]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--labels", required=True, help="LLM label run(s) for DICES-990 in results/llm_labels")
    ap.add_argument("--labels350", nargs="*", default=[], help="LLM label runs covering DICES-350")
    args = ap.parse_args()

    out, md = {"990": [], "350": []}, [
        "# FUSE on DICES-990 against an LLM safety label (generated by scripts/run_dices990.py)", "",
        f"Reference label: `{args.labels}` (results/llm_labels). DICES-990 has no expert label, so every "
        "accuracy below is agreement with the LLM label, not with experts.", "",
    ]
    lab = read_labels([args.labels])
    df = dices.load("990")
    md += ["## DICES-990", ""]
    for view, groups, min_items in SETTINGS_990:
        m = dices.with_reference(matrix(df, view, groups, min_items), lab.item_id, lab.unsafe)
        start = time.time()
        r = dices.evaluate(m, FUSE(), label_fracs=(0.10,))
        r["missing_share"] = float(np.isnan(m.V).mean())
        print(r["summary"], f"({time.time() - start:.0f}s)")
        print(dices.format_table(r), "\n", flush=True)
        out["990"].append(r)
        md += block(r)

    if args.labels350:
        lab350 = read_labels(args.labels350)
        df350 = dices.load("350")
        md += ["## DICES-350: the same runs scored against the expert label and against the LLM label", "",
               f"LLM label runs: {', '.join(args.labels350)} ({len(lab350)} conversations).", ""]
        for view, groups, min_items in SETTINGS_350:
            base = matrix(df350, view, groups, min_items)
            for ref_name, ids, ys in (("expert label", base.items, base.gold), ("LLM label", lab350.item_id, lab350.unsafe)):
                m = dices.with_reference(base, ids, ys)
                r = dices.evaluate(m, FUSE(), label_fracs=(0.10,))
                r["reference"] = ref_name
                print(r["summary"], "| reference:", ref_name)
                print(dices.format_table(r), "\n", flush=True)
                out["350"].append(r)
                md += block(r, f" — reference: {ref_name}")

    (RESULTS / "dices990.json").write_text(json.dumps(out, indent=2))
    (RESULTS / "DICES990.md").write_text("\n".join(md))


if __name__ == "__main__":
    main()
