"""Simulation: zero-imputed vs missing-aware FUSE as ratings go missing.

    python scripts/sim_missing.py        # writes results/MISSING_SIM.md

Binary raters with known sensitivity/specificity under conditional independence. Each rating
is observed with probability `rate` (random assignment) or, in the label-dependent design,
with 1.5x that probability for positive items (as in enriched reader studies such as VIPER).
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from fuse import FUSE  # noqa: E402
from fuse.dices import dawid_skene  # noqa: E402

N, M, PREV, SEEDS = 2000, 30, 0.3, 5
RATES = [1.0, 0.5, 0.25, 0.1, 0.05]


def simulate(rate, design, rng):
    psi, eta = rng.uniform(0.55, 0.85, M), rng.uniform(0.55, 0.85, M)
    y = rng.random(N) < PREV
    u = rng.random((N, M))
    V = np.where(np.where(y[:, None], u < psi, u >= eta), 1.0, -1.0)
    p = np.where(y, min(1.0, 1.5 * rate), rate) if design == "label-dependent" else np.full(N, rate)
    V[rng.random(V.shape) >= p[:, None]] = np.nan
    return V, y, psi, eta


def run_one(V, y, psi, eta):
    acc = lambda s: 100 * float(((s > 0.5) == y).mean())  # noqa: E731
    obs = ~np.isnan(V)
    with np.errstate(invalid="ignore"):
        share = np.nansum(V > 0, 1) / np.maximum(obs.sum(1), 1)
    share = np.where(obs.any(1) & (share != 0.5), share, np.random.default_rng(0).random(len(y)))  # ties/no rating: coin
    out = {"Majority vote": acc(share), "Dawid-Skene": acc(dawid_skene(V))}
    Z = np.nan_to_num(V)
    r = FUSE(predictor="posterior").fit_scores(Z, rescale=False)
    out["FUSE, missing = 0 (paper)"] = acc(r.scores)
    err = {}
    if r.estimate is not None:
        est = r.estimate
        err["FUSE, missing = 0 (paper)"] = float(np.mean(np.abs(np.r_[est.psi - psi[r.kept], est.eta - eta[r.kept]])))
    for name, kw in [("FUSE skip, triplet posterior", {}), ("FUSE skip, product posterior", {"posterior_mode": "product"}),
                     ("FUSE skip + EM", {"posterior_mode": "product", "em_refine": True})]:
        try:
            r = FUSE(missing="skip", predictor="posterior", **kw).fit_scores(V, rescale=False)
            out[name] = acc(r.scores)
            if name.endswith("triplet posterior") and r.estimate is not None:
                err["FUSE skip"] = float(np.mean(np.abs(np.r_[r.estimate.psi - psi[r.kept], r.estimate.eta - eta[r.kept]])))
        except Exception as e:  # too sparse for any observed pair/triplet
            out[name] = float("nan")
            print("  ", name, "failed:", type(e).__name__, e)
    return out, err


def main():
    md = ["# Missing ratings: simulation (generated by scripts/sim_missing.py)", "",
          f"{N} items, {M} binary raters, prevalence {PREV}, sensitivity and specificity uniform on [0.55, 0.85], "
          f"conditional independence. Accuracy against the true label, mean over {SEEDS} seeds. "
          "Ratings per item = 30 x observed rate. 'Param. error' = mean |estimated - true| sensitivity/specificity "
          "of the verifiers FUSE kept.", ""]
    for design in ["random", "label-dependent"]:
        rows, names = [], None
        for rate in RATES:
            if design == "label-dependent" and rate == 1.0:
                continue
            res, errs = [], []
            for seed in range(SEEDS):
                V, y, psi, eta = simulate(rate, design, np.random.default_rng(seed))
                o, e = run_one(V, y, psi, eta)
                res.append(o)
                errs.append(e)
            names = list(res[0])
            row = {k: np.nanmean([r[k] for r in res]) for k in names}
            for k, label in [("FUSE, missing = 0 (paper)", "Param. error, missing = 0"), ("FUSE skip", "Param. error, skip")]:
                row[label] = np.nanmean([e.get(k, np.nan) for e in errs])
            rows.append((rate, row))
            print(design, rate, {k: round(v, 1) if v > 1 else round(v, 3) for k, v in row.items()}, flush=True)
        cols = list(rows[0][1])
        md += [f"## Assignment: {design}", "", "| Observed rate | " + " | ".join(cols) + " |", "|---:|" + "---:|" * len(cols)]
        for rate, row in rows:
            md.append(f"| {int(100 * rate)}% | " + " | ".join(f"{row[c]:.3f}" if c.startswith("Param") else f"{row[c]:.1f}" for c in cols) + " |")
        md.append("")
    (ROOT / "results" / "MISSING_SIM.md").write_text("\n".join(md))


if __name__ == "__main__":
    main()
