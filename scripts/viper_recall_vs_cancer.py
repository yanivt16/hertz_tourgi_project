"""VIPER: radiologists' recall decisions against cancer, and whether a label-free method can tell
which radiologists are good.

    pip install rdata
    python scripts/viper_recall_vs_cancer.py      # writes results/VIPER_RECALL.md

Three questions:
1. How often is a cancer not recalled, per read and per case?
2. How do recall rates differ by the case's original screening outcome (BI-RADS 0 = recalled in the
   original screening but no cancer; BI-RADS 1-3 = not recalled, no cancer; cancer)?
3. Dawid-Skene and FUSE, fitted on recall decisions only, estimate each reader's sensitivity and
   specificity. How well do these rank the readers against their true values? For FUSE we use its
   method-of-moments estimator directly on the +/-1 recall decisions (the threshold search has
   nothing to choose on binary data): the missing-aware version on the full matrix, the paper's on
   dense blocks. No readers are dropped, so every reader gets an estimate.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
from scipy.stats import spearmanr  # noqa: E402
from sklearn.metrics import roc_auc_score  # noqa: E402

from fuse import viper  # noqa: E402
from fuse.missing import masked_mom_estimate  # noqa: E402
from fuse.moments import mom_estimate  # noqa: E402

np.seterr(all="ignore")  # spurious matmul warnings from macOS Accelerate; results unaffected


def ds_rates(B: np.ndarray, n_iter: int = 200):
    """Binary Dawid-Skene that skips missing reads; same model and smoothing as
    fuse.dices.dawid_skene, but returns per-reader sensitivity and specificity as well."""
    M = (~np.isnan(B)).astype(float)
    X = np.nan_to_num(B)
    q = (X.sum(1) / np.maximum(M.sum(1), 1)).clip(1e-3, 1 - 1e-3)
    for _ in range(n_iter):
        prior = q.mean().clip(1e-3, 1 - 1e-3)
        se = ((q[:, None] * X).sum(0) + 1) / ((q[:, None] * M).sum(0) + 2)
        sp = (((1 - q)[:, None] * (M - X)).sum(0) + 1) / (((1 - q)[:, None] * M).sum(0) + 2)
        l1 = np.log(prior) + X @ np.log(se) + (M - X) @ np.log(1 - se)
        l0 = np.log(1 - prior) + (M - X) @ np.log(sp) + X @ np.log(1 - sp)
        q = 1 / (1 + np.exp(np.clip(l0 - l1, -50, 50)))
    return se, sp, q


def rho(a, b) -> str:
    return f"{spearmanr(a, b).correlation:+.2f}"


def main():
    reads, gold = viper.load()
    reads = reads.assign(rec=(reads.recall.astype(str) == "1").astype(int),
                         grp=reads.Ctype.astype(str).str.replace("ffdm", "").str.replace("sfm", ""))
    out = ["# VIPER: recall decisions against cancer (generated by scripts/viper_recall_vs_cancer.py)", "",
           "Each read has a recall decision (send for further work-up or not) and the gold label is cancer "
           "status at 455-day follow-up. Non-cancer cases carry their outcome in the original screening "
           "(`Ctype`): BI-RADS 0 means recalled for further imaging, BI-RADS 1-3 means not recalled. "
           "Sensitivity = share of cancer reads recalled; specificity = share of non-cancer reads not recalled; "
           "skill (Youden J) = sensitivity + specificity - 1.", ""]
    for mod, R in reads.groupby("modalityID"):
        R = R.assign(y=R.caseID.map(gold))
        items, ws = sorted(R.caseID.unique()), sorted(R.readerID.unique())
        B = R.pivot(index="caseID", columns="readerID", values="rec").reindex(index=items, columns=ws).to_numpy(float)
        y = gold.reindex(items).to_numpy()
        g = R.groupby("readerID")
        tr = pd.DataFrame({"rate": g.rec.mean(),
                           "sens": R[R.y == 1].groupby("readerID").rec.mean(),
                           "spec": 1 - R[R.y == 0].groupby("readerID").rec.mean(),
                           "cancers": R[R.y == 1].groupby("readerID").size()}).reindex(ws)
        tr["J"] = tr.sens + tr.spec - 1

        C = B[y == 1]
        nread, nrec = (~np.isnan(C)).sum(1), np.nansum(C, 1)
        out += [f"## {mod}", "",
                f"{len(items)} cases ({int(y.sum())} cancers), {len(ws)} readers, {np.isnan(B).mean():.0%} missing.", "",
                "### 1. Cancers that were not recalled", "",
                "| | Value |", "|---|---:|",
                f"| Cancer reads not recalled | {int(nread.sum() - nrec.sum())} of {int(nread.sum())} ({1 - nrec.sum() / nread.sum():.0%}) |",
                f"| Cancer cases recalled by fewer than half their readers | {(nrec / nread < 0.5).sum()} of {len(C)} |",
                f"| Cancer cases recalled by no reader | {(nrec == 0).sum()} (each is read by {nread.min()}-{nread.max()} readers) |",
                f"| Cancer cases recalled by every reader | {(nrec == nread).sum()} |",
                f"| Per-reader sensitivity, median [range] | {tr.sens.median():.0%} [{tr.sens.min():.0%}-{tr.sens.max():.0%}] |",
                f"| Per-reader specificity, median [range] | {tr.spec.median():.0%} [{tr.spec.min():.0%}-{tr.spec.max():.0%}] |", "",
                "### 2. Recall rate by the case's original screening outcome", "",
                "| Case type | Cases | Reads | Recall rate | Per-reader recall rate, median [range] |", "|---|---:|---:|---:|---|"]
        per = R.groupby(["readerID", "grp"]).rec.mean().unstack()
        labels = {"birads0": "No cancer, recalled in original screening (BI-RADS 0)",
                  "birads123": "No cancer, not recalled (BI-RADS 1-3)", "cancer": "Cancer"}
        for k, d in R.groupby("grp"):
            out.append(f"| {labels.get(k, k)} | {d.caseID.nunique()} | {len(d)} | {d.rec.mean():.0%} | "
                       f"{per[k].median():.0%} [{per[k].min():.0%}-{per[k].max():.0%}] |")
        se, sp, q = ds_rates(B)
        fe = masked_mom_estimate(np.where(np.isnan(B), np.nan, 2 * B - 1), min_overlap=20)
        fse, fsp = np.clip(fe.psi, 0, 1), np.clip(fe.eta, 0, 1)
        out += ["", "### 3. Do Dawid-Skene and FUSE, without labels, rank the readers correctly?", "",
                "Spearman correlation across readers between each method's estimate (fitted on recall decisions "
                "only) and the true value. 'Recall rate' is shown because it drives both sensitivity and specificity.", "",
                "| Full matrix (all readers) | Dawid-Skene | FUSE (missing-aware MoM) | Recall rate alone |", "|---|---:|---:|---:|",
                f"| Estimated vs true sensitivity | {rho(se, tr.sens)} | {rho(fse, tr.sens)} | {rho(tr.rate, tr.sens)} |",
                f"| Estimated vs true specificity | {rho(sp, tr.spec)} | {rho(fsp, tr.spec)} | {rho(tr.rate, tr.spec)} |",
                f"| Estimated vs true skill (J) | {rho(se + sp - 1, tr.J)} | {rho(fse + fsp - 1, tr.J)} | {rho(tr.rate, tr.J)} |",
                f"| Estimated skill vs recall rate | {rho(se + sp - 1, tr.rate)} | {rho(fse + fsp - 1, tr.rate)} | |", "",
                f"FUSE mean estimated sensitivity {fse.mean():.2f}, specificity {fsp.mean():.2f}.", "",
                f"Dawid-Skene mean estimated vs true: sensitivity {se.mean():.2f} vs {tr.sens.mean():.2f}, specificity "
                f"{sp.mean():.2f} vs {tr.spec.mean():.2f}. D&S posterior AUC against cancer: {roc_auc_score(y, q):.3f}. "
                f"Readers read {tr.cancers.min()}-{tr.cancers.max()} cancer cases each.", ""]
        blocks = viper.dense_blocks(R)
        if blocks:
            out += ["Dense blocks (every reader read every case, so no missing reads and no assignment leak):", "",
                    "| Block | D&S sensitivity | D&S specificity | D&S skill (J) | FUSE sensitivity | FUSE specificity | FUSE skill (J) |", "|---|---:|---:|---:|---:|---:|---:|"]
            for n_cases, (rs, cs) in sorted(blocks.items()):
                Rb = R[R.readerID.isin(rs) & R.caseID.isin(cs)]
                yb = gold.reindex(sorted(Rb.caseID.unique())).to_numpy()
                Bb = Rb.pivot(index="caseID", columns="readerID", values="rec").reindex(index=sorted(Rb.caseID.unique()), columns=rs).to_numpy(float)
                ts = np.array([Bb[yb == 1, j].mean() for j in range(len(rs))])
                tp = np.array([1 - Bb[yb == 0, j].mean() for j in range(len(rs))])
                bse, bsp, _ = ds_rates(Bb)
                bf = mom_estimate(2 * Bb - 1)
                fs, fp = np.clip(bf.psi, 0, 1), np.clip(bf.eta, 0, 1)
                out.append(f"| {len(rs)} readers x {n_cases} cases ({int(yb.sum())} cancers) | {rho(bse, ts)} | "
                           f"{rho(bsp, tp)} | {rho(bse + bsp - 1, ts + tp - 1)} | {rho(fs, ts)} | {rho(fp, tp)} | "
                           f"{rho(fs + fp - 1, ts + tp - 1)} |")
            out.append("")
    path = ROOT / "results" / "VIPER_RECALL.md"
    path.write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
