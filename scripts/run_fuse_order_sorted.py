"""Follow-up to scripts/run_fuse_order.py: does a label-free column order fix FUSE? Columns sorted by
the detector's robust quality estimate (trimmed rank-one loadings, fuse.clustering.residual_corr),
strongest first or last, against the original order (humans first) and the best of the four
baselines of run_fuse_order.py, taken per draw (an optimistic baseline).

    python scripts/run_fuse_order_sorted.py      # writes results/FUSE_ORDER_SORTED.md
"""
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts")); sys.path.insert(0, str(ROOT / "src"))
import numpy as np, pandas as pd
from sklearn.metrics import roc_auc_score
import run_fuse_order as O
from fuse import FUSE, crowd, dices
from fuse.clustering import residual_corr
np.seterr(all="ignore")
def fuse_sorted(V, desc=True):
    _, u, _ = residual_corr(V); o = np.argsort(-u if desc else u)
    return FUSE().fit_scores(V[:, o]).scores
OUT = ['# FUSE with columns sorted by estimated quality (generated by scripts/run_fuse_order_sorted.py)', '',
       '| Panel | FUSE, original order | Strongest first | Strongest last | Best baseline (per draw) | Strongest first minus best |', '|---|---:|---:|---:|---:|---:|']
def run(name, draws):
    r = {"orig": [], "strong first": [], "strong last": [], "best base": []}
    for V, y in draws:
        a = lambda s: 100 * roc_auc_score(y, s)
        r["orig"].append(a(FUSE().fit_scores(V).scores)); r["strong first"].append(a(fuse_sorted(V))); r["strong last"].append(a(fuse_sorted(V, False)))
        r["best base"].append(max(a(s) for s in O.baselines(V).values()))
    r = {k: np.array(v) for k, v in r.items()}; d = r["strong first"] - r["best base"]
    OUT.append(f"| {name} | {r['orig'].mean():.1f} | {r['strong first'].mean():.1f} | {r['strong last'].mean():.1f} | "
               f"{r['best base'].mean():.1f} | {d.mean():+.1f} ± {1.96*d.std()/np.sqrt(len(d)):.1f} |"); print(OUT[-1], flush=True)
for h, d, rho in [(5, 0.3, 0.0), (5, 0.3, 0.15), (5, 0.5, 0.15), (5, 0.5, 0.2), (10, 0.3, 0.3), (10, 0.3, 0.6)]:
    run(f"sim {h} humans, d={d}, rho={rho}", [O.simulate(np.random.default_rng(s), 1000, h, 6, d, rho) for s in range(10)])
import run_correlated_block_rte as R
Hr, gold = crowd.load("RTE"); yr = gold.astype(int)
Xr = {mm: np.column_stack([R.llm(mm, p) for p in ("short", "guide")]) for mm in R.SMALL}
for name, nh, models in [("RTE 10 humans + 4 tiny", 10, R.TINY), ("RTE 5 humans + 4 tiny", 5, R.TINY), ("RTE 3 humans + 4 tiny", 3, R.TINY)]:
    run(name, [(np.c_[R.slots(Hr, np.random.default_rng(dd))[:, :nh], np.column_stack([Xr[mm] for mm in models])], yr) for dd in range(20)])

(ROOT / "results" / "FUSE_ORDER_SORTED.md").write_text("\n".join(OUT + [""]))
