"""The one regime where the simulation puts FUSE ahead, on real data: a dense panel of humans next to a
minority block of weaker raters who share errors.

    python scripts/run_correlated_block_rte.py     # writes results/CORRELATED_BLOCK_RTE.md

RTE (Snow et al. 2008): 800 entailment pairs, 10 MTurk labels per pair, gold label, 50% positive.
* Human columns: each pair's 10 labels are shuffled into 10 "slots", so slot j is a dense column of
  yes/no votes from different workers. Different workers per pair keeps the slots close to
  conditionally independent. Reshuffled on every draw.
* Correlated block: small models from one family (Qwen2.5-0.5B, Qwen3-0.6B, Qwen2.5-1.5B,
  Qwen3-1.7B, 4-bit MLX), each with the two prompts of scripts/label_rte_local.py. Score =
  log P(Yes) - log P(No).
Panels vary the block's share of the panel (17% to 57%).

Methods (all label-free). Binary human columns are used as they are; LLM scores are cut at each
column's median for the yes/no methods.
  MV, Dawid-Skene (yes/no), Dawid-Skene on 5 quantile bins, mean z-score,
  D&S -> logistic (the FUSE logistic step fed with Dawid-Skene posteriors instead of FUSE's),
  FUSE logistic and FUSE triplet posterior (paper), FUSE logistic with median thresholds (no TCI search).
AUC, mean over DRAWS slot shuffles. The 95% interval resamples both the draw and the items.
"""

from __future__ import annotations

import sys
import warnings
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from fuse import FUSE, crowd  # noqa: E402
from fuse.dices import dawid_skene  # noqa: E402
from fuse.ordinal import dawid_skene_ordinal  # noqa: E402
from fuse.preprocess import minmax_to_unit_interval  # noqa: E402

warnings.filterwarnings("ignore")
DRAWS = 20
TINY = ["Qwen2.5-0.5B-Instruct-4bit", "Qwen3-0.6B-4bit"]
SMALL = TINY + ["Qwen2.5-1.5B-Instruct-4bit", "Qwen3-1.7B-4bit"]
PANELS = [  # (name, human slots, models in the block)
    ("10 humans", 10, []),
    ("10 humans + 2 tiny (17%)", 10, TINY[:1]),
    ("10 humans + 4 tiny (29%)", 10, TINY),
    ("10 humans + 8 small Qwen (44%)", 10, SMALL),
    ("5 humans", 5, []),
    ("5 humans + 4 tiny (44%)", 5, TINY),
    ("3 humans", 3, []),
    ("3 humans + 4 tiny (57%)", 3, TINY),
    ("4 tiny only", 0, TINY),
    ("8 small Qwen only", 0, SMALL),
]
REF = "D&S (5 bins)"


def llm(model, prompt):
    f = ROOT / "results" / "llm_scores" / f"rte_{model}_{prompt}.csv"
    return pd.read_csv(f).sort_values("item_id").logit_yes.to_numpy()


def slots(H, rng):
    """Items x 10 dense matrix: each item's labels in random order."""
    out = np.empty((len(H), 10))
    for i in range(len(H)):
        v = H[i, ~np.isnan(H[i])]
        out[i] = rng.permutation(v)[:10]
    return out


def methods(V, binary):
    B = np.where(binary[None, :], V, np.where(V > np.median(V, 0), 1.0, -1.0))
    sd = V.std(0)
    Z = (V - V.mean(0)) / np.where(sd > 0, sd, 1)
    tie = np.random.default_rng(0).random(len(V)) * 1e-6
    ds = dawid_skene(B)
    return {"Majority vote": B.mean(1) + tie,
            "Dawid-Skene": ds,
            REF: dawid_skene_ordinal(V, 5),
            "Mean z-score": Z.mean(1) + tie,
            "D&S -> logistic": FUSE()._predict(minmax_to_unit_interval(V), ds),
            "FUSE logistic (paper)": FUSE().fit_scores(V).scores,
            "FUSE posterior (paper)": FUSE(predictor="posterior").fit_scores(V).scores,
            "FUSE logistic, median thresholds": FUSE(n_sweeps=0).fit_scores(V).scores}


def within_class_corr(V, y, a, b):
    """Mean within-class correlation between columns in group a and columns in group b."""
    vals = []
    for c in (0, 1):
        C = np.corrcoef(V[y == c].T)
        P = np.outer(a, b) | np.outer(b, a) if a is not b else np.outer(a, a)
        np.fill_diagonal(P, False)
        vals.append(np.nanmean(C[P]))
    return float(np.mean(vals))


def boot(runs, k1, k2, y, n=2000, seed=0):
    rng = np.random.default_rng(seed)
    d = []
    for _ in range(n):
        r = runs[rng.integers(len(runs))]
        i = rng.integers(0, len(y), len(y))
        d.append(roc_auc_score(y[i], r[k1][i]) - roc_auc_score(y[i], r[k2][i]))
    mean = np.mean([roc_auc_score(y, r[k1]) - roc_auc_score(y, r[k2]) for r in runs])
    lo, hi = np.percentile(d, [2.5, 97.5])
    return f"{100 * mean:+.1f} [{100 * lo:+.1f}, {100 * hi:+.1f}]"


def main():
    H, gold = crowd.load("RTE")
    y = gold.astype(int)
    assert (np.sum(~np.isnan(H), 1) == 10).all()
    X = {m: np.column_stack([llm(m, p) for p in ("short", "guide")]) for m in SMALL}

    md = ["# A correlated block of small LLMs next to humans, RTE (generated by scripts/run_correlated_block_rte.py)", "",
          f"800 pairs, 50% positive. AUC, mean over {DRAWS} shuffles of each pair's 10 labels into 10 human "
          "columns. Intervals: 95%, resampling draws and items.", "",
          "## The raters", "", "| Rater | AUC | Accuracy |", "|---|---:|---:|",
          f"| One human label (mean over slots) | {100 * np.mean([roc_auc_score(y, s) for s in slots(H, np.random.default_rng(0)).T]):.1f} "
          f"| {100 * np.nanmean((H > 0) == y[:, None], where=~np.isnan(H)):.1f} |"]
    for m in SMALL:
        for j, p in enumerate(("short", "guide")):
            md.append(f"| {m}, {p} | {100 * roc_auc_score(y, X[m][:, j]):.1f} | {100 * np.mean((X[m][:, j] > 0) == y):.1f} |")
    S0 = slots(H, np.random.default_rng(0))
    T = np.column_stack([X[m] for m in TINY])
    V0 = np.c_[S0, T]
    h = np.r_[np.ones(10, bool), np.zeros(4, bool)]
    md += ["", "Within-class correlation (conditional dependence): "
           f"human-human {within_class_corr(V0, y, h, h):.2f}, tiny LLM-tiny LLM {within_class_corr(V0, y, ~h, ~h):.2f}, "
           f"human-tiny LLM {within_class_corr(V0, y, h, ~h):.2f}.", ""]
    print("\n".join(md), flush=True)

    keys = None
    table = []
    for name, k, models in PANELS:
        runs = []
        for d in range(DRAWS if k else 1):
            S = slots(H, np.random.default_rng(d))[:, :k]
            L = np.column_stack([X[m] for m in models]) if models else np.empty((len(y), 0))
            V = np.c_[S, L]
            binary = np.r_[np.ones(k, bool), np.zeros(L.shape[1], bool)]
            runs.append(methods(V, binary))
        keys = keys or list(runs[0])
        auc = {m: 100 * np.mean([roc_auc_score(y, r[m]) for r in runs]) for m in keys}
        table.append((name, auc, boot(runs, "FUSE logistic (paper)", REF, y), boot(runs, "FUSE logistic (paper)", "D&S -> logistic", y),
                      boot(runs, "FUSE logistic (paper)", "Mean z-score", y)))
        print(name, {m: round(v, 1) for m, v in auc.items()}, table[-1][2:], flush=True)

    md += ["## Panels", "", "| Panel | " + " | ".join(keys) + " | FUSE logistic vs D&S 5 bins | FUSE logistic vs D&S -> logistic | FUSE logistic vs mean z |",
           "|---|" + "---:|" * len(keys) + "---|---|---|"]
    for name, auc, b1, b2, b3 in table:
        best = max(auc.values())
        md.append(f"| {name} | " + " | ".join(f"**{v:.1f}**" if v == best else f"{v:.1f}" for v in auc.values()) + f" | {b1} | {b2} | {b3} |")
    md.append("")
    (ROOT / "results" / "CORRELATED_BLOCK_RTE.md").write_text("\n".join(md))
    print("\n".join(md[-len(table) - 3:]))


if __name__ == "__main__":
    main()
