"""Small random rater panels: majority vote vs Dawid–Skene vs FUSE inside each panel (DICES-350).

Hypothesis: with all 123 raters the few good raters are drowned out by the crowd, and in a
small panel they weigh more, so a method that learns rater quality without labels (FUSE)
should gain most there.

Each repetition shuffles the 123 raters and cuts them into disjoint panels of about `size`
(123 // size panels, e.g. 12 panels of 10–11). Inside each panel every method sees only that
panel's raters, one verifier per rater, on all 350 conversations (scripts/panel_eval.py has the
methods). The comparison is like for like:

* Same information: the main Dawid–Skene uses all three answers (Yes / Unsure / No), as FUSE and
  majority vote do. The Yes-only and Unsure-as-Yes versions are reported beside it.
* Same cut-off: besides each method's own rule (> 0.5), accuracy is scored with every method
  calling the same number of conversations unsafe, at FUSE's estimated prevalence and at
  three-answer Dawid–Skene's. Cutting each method at its OWN estimate (the first version of this
  script) rewards whichever method under-calls less.

No label is used to fit anything. The cut-off at an estimated prevalence was adopted for FUSE on
the dev half of DICES-350 (scripts/tune_dices350.py), so accuracy is also given on the test half.

    python scripts/dices_small_panels.py --reps 100 --sizes 5 10 20
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import time
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
sys.path.insert(0, str(ROOT / "src"))

import panel_eval as PE  # noqa: E402
import tune_dices350 as T  # noqa: E402

_V = _Y = None


def _init(V, y):
    global _V, _Y
    _V, _Y = V, y


def one_rep(args):
    size, rep = args
    perm = np.random.default_rng(20_000 + rep).permutation(_V.shape[1])
    return [PE.evaluate_panel(_V[:, cols], _Y) for cols in np.array_split(perm, _V.shape[1] // size)]


def fmt_pair(p):
    return (f"| {p['a']} − {p['b']} | {p['cut']} | {p['diff']:+.2f} | {p['a_wins']:.0f} / {p['tie']:.0f} / {p['b_wins']:.0f} | "
            f"[{p['lo']:+.2f}, {p['hi']:+.2f}] |")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--reps", type=int, default=100)
    ap.add_argument("--sizes", type=int, nargs="*", default=[5, 10, 20])
    ap.add_argument("--workers", type=int, default=max(1, (os.cpu_count() or 2) - 1))
    a = ap.parse_args()

    d = T.Data()
    V, y, test = d.raters_V, d.gold, ~d.dev
    assert not np.isnan(V).any()
    full = PE.evaluate_panel(V, y)
    out = {"reps": a.reps, "all_123": {m: {c: 100 * float(full["hits"][m][c].mean()) for c in PE.CUTS} | {"auc": full["auc"][m]}
                                        for m in PE.METHODS}, "sizes": {}}
    md = ["# Small random rater panels on DICES-350 (generated by scripts/dices_small_panels.py)", "",
          f"{a.reps} reshuffles of the 123 raters per panel size, each cut into disjoint panels. Inside each panel every "
          "method sees only that panel's raters. Accuracy (%) against the expert label on all 350 conversations unless a "
          "column says test half (176). **Natural**: each method's own rule (score > 0.5). **At FUSE est. / at DS-3 est.**: "
          "every method calls the same number of conversations unsafe, set by FUSE's or three-answer Dawid–Skene's estimated "
          "prevalence. Intervals: each conversation's hit rate averaged over all panels, paired bootstrap over conversations; "
          "they say whether a gap would hold on new conversations for this pool of 123 raters, not for new raters.", "",
          "## All 123 raters (one panel)", "", "| Method | Natural | At FUSE est. | At DS-3 est. | AUC |", "|---|---:|---:|---:|---:|"]
    md += [f"| {m} | {v['natural']:.1f} | {v['at FUSE est.']:.1f} | {v['at DS-3 est.']:.1f} | {v['auc']:.1f} |" for m, v in out["all_123"].items()]
    md.append("")
    for size in a.sizes:
        t0 = time.time()
        with ProcessPoolExecutor(a.workers, initializer=_init, initargs=(V, y)) as pool:
            rows = [r for res in pool.map(one_rep, [(size, r) for r in range(a.reps)], chunksize=4) for r in res]
        allm, testm = PE.summarize(rows), PE.summarize(rows, test)
        pairs = []
        for cut in PE.CUTS:
            pairs.append(PE.paired(rows, "FUSE", "Dawid–Skene, 3 answers", cut))
            pairs.append({**PE.paired(rows, "FUSE", "Dawid–Skene, 3 answers", cut, test), "cut": cut + ", test half"})
        pairs.append(PE.paired(rows, "FUSE", "Dawid–Skene, Yes only", "natural"))
        pairs.append(PE.paired(rows, "FUSE", "Majority vote", "natural"))
        pairs.append(PE.paired(rows, "FUSE", "Majority vote", "at FUSE est."))
        pairs.append(PE.paired(rows, "Dawid–Skene, 3 answers", "Majority vote", "at DS-3 est."))
        aucs = [PE.paired_auc(rows, "FUSE", b) for b in ["Dawid–Skene, 3 answers", "Dawid–Skene, Yes only", "Dawid–Skene, Unsure as Yes", "Majority vote"]]
        mv_info = float(np.mean([r["auc"]["Majority vote"] - r["auc_mv_unsure_no"] for r in rows]))
        rho = PE.rho_summary(rows)
        est = {"fuse": float(np.nanmean([r["fuse_est_prev"] if r["fuse_est_prev"] is not None else np.nan for r in rows])),
               "ds3": float(np.mean([r["ds3_est_prev"] for r in rows])), "fallbacks": sum(r["fuse_fallback"] is not None for r in rows)}
        best = float(np.mean([r["best_rater_acc"] for r in rows]))
        out["sizes"][str(size)] = {"panels": len(rows), "all": allm, "test": testm, "pairs": pairs, "auc_pairs": aucs,
                                   "mv_auc_unsure_half_minus_no": mv_info, "rho": rho, "est_prev": est, "best_rater_acc": best}
        print(f"size {size}: {len(rows)} panels ({time.time() - t0:.0f}s)", flush=True)

        md += [f"## Panels of about {size} raters ({len(rows)} panels)", "",
               f"Estimated unsafe share, mean over panels: FUSE {est['fuse']:.2f}, three-answer Dawid–Skene {est['ds3']:.2f} "
               f"(experts 0.50). FUSE fell back to a plain average in {est['fallbacks']} panels. Best single rater in a panel "
               f"(picked with the labels): {best:.1f}.", "",
               "| Method | Natural | At FUSE est. | At DS-3 est. | At FUSE est., test half | AUC | Called unsafe % (natural) |",
               "|---|---:|---:|---:|---:|---:|---:|"]
        for meth in PE.METHODS:
            s, st = allm[meth], testm[meth]
            md.append(f"| {meth} | {s['natural']:.1f} | {s['at FUSE est.']:.1f} | {s['at DS-3 est.']:.1f} | {st['at FUSE est.']:.1f} | "
                      f"{s['auc']:.1f} | {s['called']:.0f} |")
        md += ["", "| Comparison | Cut-off | Mean difference | A wins / tie / B wins (% of panels) | Over conversations (95% CI) |",
               "|---|---|---:|---|---|"]
        md += [fmt_pair(p) for p in pairs]
        md += ["", "| AUC comparison | Mean difference | A higher in % of panels | Middle 95% of panels |", "|---|---:|---:|---|"]
        md += [f"| {p['a']} − {p['b']} | {p['diff']:+.2f} | {p['a_wins']:.0f} | {p['p2.5']:+.1f} to {p['p97.5']:+.1f} |" for p in aucs]
        md += ["", f"Majority vote's AUC with Unsure as 1/2 minus with Unsure as No: {mv_info:+.2f} (what Unsure is worth).", "",
               f"**Does the method find the good raters?** Spearman between estimated and true rater quality, mean over panels: "
               f"FUSE {rho['fuse']:+.2f}, three-answer Dawid–Skene {rho['ds3']:+.2f}; FUSE's is higher in {rho['fuse_higher_share']:.0f}% "
               f"of {rho['n']} panels.", ""]
        (ROOT / "results" / "DICES_SMALL_PANELS.md").write_text("\n".join(md) + "\n")
        (ROOT / "results" / "dices_small_panels.json").write_text(json.dumps(out, indent=1))


if __name__ == "__main__":
    main()
