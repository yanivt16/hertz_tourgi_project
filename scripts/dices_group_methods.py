"""Other aggregation methods on the same grouped views that FUSE was tuned on (DICES-350).

The tuning (scripts/tune_dices350.py) found that grouping raters by demographics is the only
large lever for FUSE. This asks whether grouping helps the other methods too. Each view is a
matrix of group shares (share of the group's raters saying unsafe, Unsure = 1/2); for the
vote-based methods each group first casts one vote, unsafe when its share is above 1/2.

Scored on the same dev/test halves as the tuning, plus all 350 for reference. Intervals are
paired bootstrap 95% intervals against per-rater majority vote on the test half.

    python scripts/dices_group_methods.py      # writes results/DICES_GROUP_METHODS.md and .json
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
sys.path.insert(0, str(ROOT / "src"))

import tune_dices350 as T  # noqa: E402
from fuse import dices  # noqa: E402

VIEWS = ["groups: race×education", "groups: race×gender", "groups: race", "random groups of 20"]


def top_share(score: np.ndarray, share: float) -> np.ndarray:
    """Call the top `share` of items unsafe (a label-free cut-off at an estimated prevalence)."""
    k = int(round(share * len(score)))
    pred = np.zeros(len(score), dtype=bool)
    pred[np.argsort(-score, kind="stable")[:k]] = True
    return pred


def methods(d: T.Data, view: str) -> tuple[dict, dict]:
    S = d.matrix(view).V  # (items, groups) share saying unsafe, in [0, 1]
    votes = S > 0.5
    q = dices.dawid_skene(votes.astype(float))
    f0 = T.predict(d, {**T.DEFAULT_CONFIG, "view": view})
    f1 = T.predict(d, {**T.DEFAULT_CONFIG, "view": view, "cutoff": "prevalence"})
    out = {
        "Majority of group votes": (votes.mean(1), votes.mean(1) > 0.5),
        "Mean of group shares > 0.5": (S.mean(1), S.mean(1) > 0.5),
        "Dawid–Skene on group votes": (q, q > 0.5),
        "Dawid–Skene, cut at its estimated prevalence": (q, top_share(q, float(q.mean()))),
        "FUSE defaults": (f0["scores"], f0["pred"]),
        "FUSE, cut at its estimated prevalence (tuned)": (f1["scores"], f1["pred"]),
    }
    return out, {"FUSE": f0["est_prev"], "Dawid–Skene": float(q.mean()), "n_groups": int(S.shape[1])}


def main():
    d = T.Data()
    y, dev = d.gold, d.dev
    test = ~dev
    mv = d.majority > 0.5
    ds = dices.dawid_skene(d.raters_V)

    def row(name, score, pred):
        acc = lambda mask: round(100 * float((pred[mask] == y[mask]).mean()), 1)  # noqa: E731
        c = T.paired(pred[test], mv[test], y[test])
        return {"method": name, "dev_acc": acc(dev), "test_acc": acc(test), "all_acc": acc(np.ones_like(dev)),
                "test_auc": round(T.metrics(score[test], pred[test], y[test])["auc"], 1),
                "called_unsafe": round(100 * float(pred.mean()), 1),
                "test_vs_mv": c["diff"], "test_vs_mv_lo": c["lo"], "test_vs_mv_hi": c["hi"]}

    out = {"reference": [row("Majority vote, per rater", d.majority, mv),
                         row("Dawid–Skene, per rater", ds, ds > 0.5)], "views": []}
    for view in VIEWS:
        res, est = methods(d, view)
        out["views"].append({"view": view, "estimated_prevalence": est,
                             "rows": [row(n, s, p) for n, (s, p) in res.items()]})
        print(view, "done", flush=True)

    hdr = ["| Method | Dev | Test | All 350 | Test AUC | Called unsafe % | Test − per-rater MV (95% CI) |",
           "|---|---:|---:|---:|---:|---:|---|"]

    def line(r):
        return (f"| {r['method']} | {r['dev_acc']:.1f} | {r['test_acc']:.1f} | {r['all_acc']:.1f} | "
                f"{r['test_auc']:.1f} | {r['called_unsafe']:.0f} | "
                f"{r['test_vs_mv']:+.1f} [{r['test_vs_mv_lo']:+.1f}, {r['test_vs_mv_hi']:+.1f}] |")

    md = ["# Other methods on grouped views, DICES-350 (generated by scripts/dices_group_methods.py)", "",
          f"Accuracy (%) against the expert label. Dev = {int(dev.sum())} conversations used to tune FUSE, "
          f"test = {int(test.sum())} held out. Group votes: a group says unsafe when more than half its raters did.",
          "", "## Per rater (reference)", "", *hdr, *[line(r) for r in out["reference"]]]
    for v in out["views"]:
        e = v["estimated_prevalence"]
        md += ["", f"## {v['view']} ({e['n_groups']} groups)", "",
               f"Estimated unsafe share: FUSE {e['FUSE']:.2f}, Dawid–Skene {e['Dawid–Skene']:.2f} (experts 0.50).", "",
               *hdr, *[line(r) for r in v["rows"]]]
    (ROOT / "results" / "DICES_GROUP_METHODS.md").write_text("\n".join(md) + "\n")
    (ROOT / "results" / "dices_group_methods.json").write_text(json.dumps(out, indent=1))


if __name__ == "__main__":
    main()
