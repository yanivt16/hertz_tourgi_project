"""Zero-imputed vs missing-aware FUSE on real annotator data.

    python scripts/run_missing_real.py      # writes results/MISSING_REAL.md

Datasets: RTE, D_PosSent, D_Product, Bluebird (gold), DICES-350 (expert label, dense),
DICES-990 (LLM label dices990_v4), VIPER FFDM/SFM recall decisions (cancer at 455 days).
"""

from __future__ import annotations

import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from fuse import FUSE, crowd, dices, viper  # noqa: E402
from fuse.dices import dawid_skene  # noqa: E402

METHODS = [
    ("FUSE, missing = 0 (paper)", None),
    ("FUSE skip, triplet posterior", {}),
    ("FUSE skip, product posterior", {"posterior_mode": "product"}),
    ("FUSE skip + EM", {"posterior_mode": "product", "em_refine": True}),
]


def boot(a, b, y, metric, n=2000, seed=0):
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, len(y), (n, len(y)))
    d = [metric(y[i], a[i]) - metric(y[i], b[i]) for i in idx if 0 < y[i].sum() < len(i)]
    lo, hi = np.percentile(d, [2.5, 97.5])
    return f"{100 * (metric(y, a) - metric(y, b)):+.1f} [{100 * lo:+.1f}, {100 * hi:+.1f}]"


def evaluate(name, V, y, auc=False):
    """V: items x raters, values in [-1, 1] (+1 = positive), NaN = missing."""
    t0 = time.time()
    obs = ~np.isnan(V)
    with np.errstate(invalid="ignore"):
        share = np.nansum(np.where(obs, (V + 1) / 2, 0), 1) / np.maximum(obs.sum(1), 1)
    tie = np.random.default_rng(0).random(len(y))
    share = np.where(obs.any(1) & (share != 0.5), share, tie)
    scores = {"Majority vote": share, "Dawid-Skene": dawid_skene(V)}
    for label, kw in METHODS:
        model = FUSE(predictor="posterior") if kw is None else FUSE(predictor="posterior", missing="skip", **kw)
        X = np.nan_to_num(V) if kw is None else V
        scores[label] = model.fit_scores(X, rescale=False).scores
    y = y.astype(int)
    if auc:
        metric = lambda yy, s: roc_auc_score(yy, s)  # noqa: E731
    else:
        metric = lambda yy, s: float(((s > 0.5) == yy).mean())  # noqa: E731
    rows = []
    for k, s in scores.items():
        rows.append({"Method": k, ("AUC" if auc else "Accuracy"): 100 * metric(y, s),
                     "vs MV (95% CI)": "" if k == "Majority vote" else boot(s, scores["Majority vote"], y, metric),
                     "vs Dawid-Skene (95% CI)": "" if k in ("Majority vote", "Dawid-Skene") else boot(s, scores["Dawid-Skene"], y, metric)})
    head = (f"{V.shape[0]} items, {V.shape[1]} raters, {100 * (1 - obs.mean()):.0f}% missing, "
            f"median {np.median(obs.sum(1)):.0f} ratings per item, positive rate {100 * y.mean():.0f}%")
    df = pd.DataFrame(rows)
    print(f"\n{name}: {head} ({time.time() - t0:.0f}s)\n{df.round(1).to_string(index=False)}", flush=True)
    return head, df


def to_md(name, head, df):
    cols = list(df.columns)
    out = [f"## {name}", "", head, "", "| " + " | ".join(cols) + " |", "|---|---:|---|---|"]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(f"{v:.1f}" if isinstance(v, float) else str(v) for v in r) + " |")
    return out + [""]


def main():
    md = ["# Missing ratings on real data (generated by scripts/run_missing_real.py)", "",
          "Every FUSE variant uses the posterior as the final predictor (the logistic step needs complete "
          "features). 'missing = 0' is the paper's convention used in all earlier DICES runs; 'skip' is "
          "missing-aware FUSE (src/fuse/missing.py). Differences are paired bootstraps, 2000 resamples.", ""]
    jobs = [(n, *crowd.load(n), False) for n in crowd.NAMES]
    m350 = dices.build(dices.load("350"), "overall")
    jobs.append(("DICES-350 (expert label)", m350.V, m350.gold, False))
    lab = pd.read_csv(ROOT / "results" / "llm_labels" / "dices990_v4.csv")
    lab = lab[lab.unsafe.notna()].drop_duplicates("item_id", keep="last")
    m990 = dices.with_reference(dices.build(dices.load("990"), "overall"), lab.item_id, lab.unsafe)
    jobs.append(("DICES-990 (LLM label dices990_v4)", m990.V, m990.gold, False))
    reads, gold = viper.load()
    for mod in ["FFDM", "SFM"]:
        S, B, yv = viper.build(reads[reads.modalityID == mod], gold)
        jobs.append((f"VIPER {mod}, recall decision (AUC vs cancer)", 2 * B - 1, yv.astype(bool), True))
    for name, V, y, auc in jobs:
        md += to_md(name, *evaluate(name, V, y, auc))
    (ROOT / "results" / "MISSING_REAL.md").write_text("\n".join(md))


if __name__ == "__main__":
    main()
