"""RTE: crowd workers, local LLM raters, or both. Which aggregator works best on each panel?

    python scripts/run_mixed_panel_rte.py     # writes results/MIXED_PANEL_RTE.md

RTE (Snow et al. 2008): 800 pairs, 164 MTurk workers, 10 labels per pair, gold = expert label,
50% positive. The crowd matrix is sparse (94% missing), so every FUSE variant is missing-aware
(missing="skip"). LLM verifiers: every results/llm_scores/rte_<model>_<prompt>.csv
(scripts/label_rte_local.py), score = log P(Yes) - log P(No), dense. No prompt was tuned on RTE.

"k workers" keeps k of each pair's 10 crowd labels at random (a different subset per pair, so
the panel stays sparse, as in a real crowd).
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from fuse import FUSE, crowd  # noqa: E402
from fuse.dices import dawid_skene  # noqa: E402
from fuse.ordinal import dawid_skene_ordinal  # noqa: E402

SEEDS = 10
KEYS = ["Majority vote", "Dawid-Skene", "D&S (5 bins)", "Mean z", "FUSE skip, triplet", "FUSE skip, product", "FUSE skip + EM"]


def load_llms(n_items):
    cols, names = [], []
    for f in sorted((ROOT / "results" / "llm_scores").glob("rte_*.csv")):
        if "limit" in f.stem:
            continue
        s = pd.read_csv(f).sort_values("item_id").logit_yes.to_numpy()
        if len(s) != n_items:
            continue
        cols.append(s)
        names.append(f.stem.replace("rte_", "").replace("-it-qat-4bit", "").replace("-Instruct-4bit", "").replace("-4bit", ""))
    return np.column_stack(cols), names


def methods(H, X):
    """H: crowd votes (+1 / -1 / NaN); X: LLM logits (dense) or None. Returns name -> P(positive)-like score."""
    votes = H if X is None else np.c_[H, np.sign(X)]  # an LLM's vote is its answer at P(Yes) = 0.5
    raw = H if X is None else np.c_[H, X]
    obs = ~np.isnan(votes)
    tie = np.random.default_rng(0).random(len(votes)) * 1e-6
    out = {"Majority vote": np.nansum(votes, 1) / obs.sum(1) + tie - 0.5e-6,
           "Dawid-Skene": dawid_skene(votes),
           "D&S (5 bins)": dawid_skene_ordinal(raw)}
    z = (raw - np.nanmean(raw, 0)) / np.where(np.nanstd(raw, 0) > 0, np.nanstd(raw, 0), 1)
    out["Mean z"] = np.nanmean(z, 1) + tie
    for name, kw in [("FUSE skip, triplet", {}), ("FUSE skip, product", {"posterior_mode": "product"}),
                     ("FUSE skip + EM", {"posterior_mode": "product", "em_refine": True})]:
        out[name] = FUSE(predictor="posterior", missing="skip", **kw).fit_scores(raw).scores
    return out


def keep_k(H, k, seed):
    rng = np.random.default_rng(seed)
    out = np.full_like(H, np.nan)
    for i in range(len(H)):
        j = np.flatnonzero(~np.isnan(H[i]))
        j = rng.choice(j, min(k, len(j)), replace=False)
        out[i, j] = H[i, j]
    return out[:, ~np.isnan(out).all(0)]


CENTRED = {"Majority vote", "Mean z"}  # scores centred at 0; the rest are probabilities


def score(y, s, m):
    return 100 * roc_auc_score(y, s), 100 * float(((s > (0 if m in CENTRED else 0.5)) == y).mean())


def main():
    H, gold = crowd.load("RTE")
    y = gold.astype(int)
    X, names = load_llms(len(y))
    print(f"{len(names)} LLM verifiers: {names}")
    md = ["# RTE: crowd workers, local LLMs, or both (generated by scripts/run_mixed_panel_rte.py)", "",
          "800 pairs, gold label, 50% positive. LLM verifiers: local open-weight models, score = "
          "log P(Yes) - log P(No) (scripts/label_rte_local.py). Accuracy thresholds: P = 0.5 for "
          "probabilities, 0 for majority vote / mean z.", ""]

    md += ["## Single LLM verifiers", "", "| Verifier | AUC | Accuracy at P(Yes) = 0.5 |", "|---|---:|---:|"]
    for j, n in enumerate(names):
        md.append(f"| {n} | {100 * roc_auc_score(y, X[:, j]):.1f} | {100 * np.mean((X[:, j] > 0) == y):.1f} |")
    C = np.corrcoef(X.T)
    fl = FUSE(predictor="logistic").fit_scores(X).scores  # the LLM block is dense, so the paper's FUSE applies
    md += ["", f"Mean pairwise correlation of LLM scores: {C[~np.eye(len(C), dtype=bool)].mean():.2f}. "
           f"Paper FUSE (logistic) on the 6 LLMs alone: AUC {100 * roc_auc_score(y, fl):.1f}, "
           f"accuracy {100 * np.mean((fl > 0.5) == y):.1f}.", ""]

    rows = []
    for k in [1, 3, 5, 10]:
        for panel in ["workers", "workers + LLMs"]:
            if panel == "workers" and k < 3:
                continue
            res = []
            for seed in range(SEEDS if k < 10 else 1):
                Hk = keep_k(H, k, seed)
                ms = methods(Hk, X if panel != "workers" else None)
                res.append({m: score(y, ms[m], m) for m in KEYS})
            row = {"k": k, "panel": panel, **{m: (np.mean([r[m][0] for r in res]), np.mean([r[m][1] for r in res])) for m in KEYS}}
            rows.append(row)
            print(k, panel, {m: tuple(round(v, 1) for v in row[m]) for m in KEYS}, flush=True)
    llm_only = {m: score(y, s, m) for m, s in methods_llm_only(X).items()}

    for idx, metric in [(0, "AUC"), (1, "Accuracy")]:
        md += [f"## Few workers, with and without LLMs: {metric}", "",
               f"Mean over {SEEDS} random draws of k labels per pair (k = 10 is the full crowd, one draw).", "",
               "| k workers | Panel | " + " | ".join(KEYS) + " |", "|---:|---|" + "---:|" * len(KEYS)]
        for r in rows:
            md.append(f"| {r['k']} | {r['panel']} | " + " | ".join(f"{r[m][idx]:.1f}" for m in KEYS) + " |")
        md.append(f"| 0 | LLMs only | " + " | ".join(f"{llm_only[m][idx]:.1f}" if m in llm_only else "" for m in KEYS) + " |")
        md.append("")
    (ROOT / "results" / "MIXED_PANEL_RTE.md").write_text("\n".join(md))
    print("\n".join(md))


def methods_llm_only(X):
    tie = np.random.default_rng(0).random(len(X)) * 1e-6
    z = (X - X.mean(0)) / X.std(0)
    return {"Majority vote": np.sign(X).mean(1) + tie - 0.5e-6, "Dawid-Skene": dawid_skene(np.sign(X)),
            "D&S (5 bins)": dawid_skene_ordinal(X), "Mean z": z.mean(1) + tie,
            "FUSE skip, product": FUSE(predictor="posterior", missing="skip", posterior_mode="product").fit_scores(X).scores}


if __name__ == "__main__":
    main()
