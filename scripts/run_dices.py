"""FUSE on DICES-350: human safety raters as verifiers, expert `safety_gold` as the label.

    python scripts/run_dices.py                   # all views, writes results/DICES.md
    python scripts/run_dices.py --views overall

The CSV is downloaded from github.com/google-research-datasets/dices-dataset into
.cache/dices on first use.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from fuse import FUSE  # noqa: E402
from fuse import dices  # noqa: E402

RESULTS = ROOT / "results"

# (view, drop quality-filtered raters, demographic grouping, extra FUSE options)
SETTINGS = [
    ("overall", False, None, {}),
    ("overall", True, None, {}),
    ("granular", False, None, {}),
    ("granular", False, None, {"tci_standardize": True}),
    ("groups", False, ("rater_race", "rater_gender"), {}),
    ("groups", False, ("rater_race", "rater_gender", "rater_age"), {}),
]


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--views", nargs="*", default=None, help="subset of overall/granular/groups (results files are only written for a full run)")
    p.add_argument("--cluster", type=float, default=None, help="FUSE cluster_threshold (off by default)")
    args = p.parse_args()

    df = dices.load("350")
    out, md = [], ["# FUSE on DICES-350 (generated by scripts/run_dices.py)", ""]
    for view, drop, groups, opts in SETTINGS:
        fuse = FUSE(cluster_threshold=args.cluster, **opts)
        if args.views and view not in args.views:
            continue
        m = dices.build(df, view=view, drop_removed=drop, groups=groups or ("rater_race", "rater_gender"))
        if groups:
            m.name += "-" + "x".join(g.replace("rater_", "") for g in groups)
        if opts:
            m.name += "-" + "-".join(k for k in opts)
        start = time.time()
        r = dices.evaluate(m, fuse)
        info = r["fuse_info"]
        print(r["summary"], f"({time.time() - start:.0f}s)")
        table = dices.format_table(r)
        print(table)
        print(
            f"FUSE kept {info['n_kept']}/{info['n_verifiers']} verifiers, estimated prevalence "
            f"{info['estimated_prevalence']}, best verifier {info['best_verifier']}\n",
            flush=True,
        )
        if not drop and view == "overall" and info.get("kept") is not None:
            removed = set(dices.REMOVED_RATERS["350"])
            dropped = set(m.verifiers) - set(info["kept"])
            info["dropped_overlap_with_quality_filter"] = len(dropped & removed)
            info["n_dropped"] = len(dropped)
        out.append(r)
        md += [f"## {m.name}", "", r["summary"], "", table, "", "```", json.dumps({k: v for k, v in info.items() if k not in ("kept", "tau")}), "```", ""]

    if args.views:
        return
    RESULTS.mkdir(exist_ok=True)
    suffix = "" if args.cluster is None else f"_cluster{args.cluster}"
    (RESULTS / f"dices350{suffix}.json").write_text(json.dumps(out, indent=2))
    (RESULTS / f"DICES{suffix}.md").write_text("\n".join(md))


if __name__ == "__main__":
    main()
